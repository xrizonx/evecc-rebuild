#!/usr/bin/env python3
"""Native Linux integration smoke test (no proprietary EVE client files needed).

Exercises key generation, CryptoAPI-compatible SIMPLEBLOB parsing, compiled.code
creation, RSA/SHA-1 signatures, and decryption of generated bytecode. This is a
synthetic compatibility test, NOT proof of interoperability with actual CCP keys.
"""
import os
import pickle
import struct
import subprocess
import sys
import tempfile
from pathlib import Path


def run(args, cwd):
    subprocess.run([str(arg) for arg in args], cwd=cwd, check=True)


def asn1_length(count):
    if count < 128:
        return bytes([count])
    payload = count.to_bytes((count.bit_length() + 7) // 8, "big")
    return bytes([0x80 | len(payload)]) + payload


def asn1_integer(value):
    data = value.to_bytes((value.bit_length() + 7) // 8, "big")
    if data[0] & 0x80:
        data = b"\x00" + data
    return b"\x02" + asn1_length(len(data)) + data


def asn1_sequence(data):
    return b"\x30" + asn1_length(len(data)) + data


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: native_smoke.py /absolute/path/to/evecc")
    binary = Path(sys.argv[1]).resolve()
    assert binary.is_file(), binary
    password = "native-ci-smoke-test"
    with tempfile.TemporaryDirectory(prefix="evecc-linux-smoke-") as base:
        root = Path(base)
        run([binary, "genkeys", "--password", password], root)
        pub = (root / "evecc.keys.pub").read_bytes()
        priv = (root / "evecc.keys.priv").read_bytes()
        assert len(pub) == 148 and pub[:2] == b"\x06\x02"
        assert len(priv) == 596 and priv[:2] == b"\x07\x02"
        # Safety regression: never overwrite an existing signing key pair.
        attempt = subprocess.run(
            [str(binary), "genkeys", "--password", password],
            cwd=root, capture_output=True, text=True)
        assert attempt.returncode != 0
        assert (root / "evecc.keys.pub").read_bytes() == pub
        assert (root / "evecc.keys.priv").read_bytes() == priv

        # A CryptoAPI SIMPLEBLOB from an exponent-of-one wrapping key stores
        # the PKCS#1 v1.5 type-2 padded secret in reverse (little-endian) order.
        tdes = bytes(range(1, 25))
        padded = b"\x00\x02" + b"\x03" * 101 + b"\x00" + tdes
        assert len(padded) == 128
        simple = bytes.fromhex("010200000366000000a40000") + padded[::-1]
        # Exercise the platform-independent binary key extraction command too.
        # This is a synthetic DLL-shaped file, not a real client DLL.
        fake_dll = root / "synthetic-blue.dll"
        fake_dll.write_bytes(bytes(40) + pub + bytes([0x7E]) * 31 + simple)
        run([binary, "dumpkeys", "-i", fake_dll], root)
        assert (root / "ccp.keys.pub").read_bytes() == pub
        assert (root / "ccp.keys.crypt").read_bytes() == simple
        again = subprocess.run([str(binary), "dumpkeys", "-i", str(fake_dll)],
                               cwd=root, capture_output=True, text=True)
        assert again.returncode != 0
        assert (root / "ccp.keys.crypt").read_bytes() == simple

        python_root = root / "script"
        src = python_root / "eve" / "client"
        src.mkdir(parents=True)
        (src / "native_port_test.py").write_text(
            "def answer():\n    return 42\nassert answer() == 42\n",
            encoding="ascii")
        output = root / "compiled.code"
        run([binary, "compilecode", "--password", password, "-o", output,
             "-I", src, "--no-cache"], root)
        assert output.is_file() and output.stat().st_size > 128

        with output.open("rb") as handle:
            magic, allout, signature = pickle.load(handle, encoding="bytes")
        assert magic == 168686339
        assert len(signature) == 128
        contents = pickle.loads(allout, encoding="bytes")
        records = contents.get(b"code", contents.get("code"))
        assert len(records) == 1

        # Check that the signature is truly valid RSA/SHA-1 rather than
        # merely having the correct size.
        exponent = struct.unpack_from("<I", pub, 16)[0]
        modulus = int.from_bytes(pub[20:148], "little")
        rsa_der = asn1_sequence(asn1_integer(modulus) + asn1_integer(exponent))
        rsa_file = root / "rsa.der"
        rsa_file.write_bytes(rsa_der)
        pem_file = root / "rsa.pem"
        run(["openssl", "rsa", "-RSAPublicKey_in", "-pubin", "-inform", "DER",
             "-in", rsa_file, "-pubout", "-out", pem_file], root)
        signed_bytes = root / "signed.bin"
        signed_bytes.write_bytes(allout)
        sig_file = root / "signature.bin"
        sig_file.write_bytes(signature[::-1])
        run(["openssl", "dgst", "-sha1", "-verify", pem_file,
             "-signature", sig_file, signed_bytes], root)

        (_, encrypted) = records[0]
        code_bytes, _sort_key = encrypted
        code_file = root / "test.pyj"
        code_file.write_bytes(code_bytes)
        decoded_file = root / "test.marshal"
        run([binary, "unpyj", "--password", password,
             "-i", code_file, "-o", decoded_file], root)
        assert decoded_file.stat().st_size > 20

        script = root / "check_marshal.py"
        script.write_text(
            "import marshal\n"
            "code = marshal.loads(open(%r, 'rb').read())\n"
            "assert code.co_name == '<module>'\n" % str(decoded_file),
            encoding="ascii")
        run([binary, "runscript", "--password", password, "-i", script], root)
        print("Native Linux integration smoke test passed")


if __name__ == "__main__":
    main()
